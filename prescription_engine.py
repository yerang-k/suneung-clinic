def get_prescription_problems(error_tag: str):
    """오류 태그에 맞는 맞춤형 기출 문항 리스트를 반환합니다."""
    return PAST_EXAM_QUESTION_INDEX.get(error_tag, [])

def evaluate_student_defense(client, problem_info: dict, student_defense: str):
    """
    학생이 방어 미션에 맞추어 작성한 선지 판단 근거를 Gemini AI가 실시간 평가하고 코칭을 제공합니다.
    """
    system_prompt = f"""
    당신은 수능 국어 메타인지 전문 코치입니다.
    학생이 이번 시험에서 범한 인지 오류를 극복하기 위해, 지정된 평가원 기출 문제에서 '방어 훈련 미션'을 수행했습니다.
    학생이 작성한 방어 근거를 읽고, 평가원의 함정 설계를 꿰뚫고 올바르게 방어했는지 냉철하면서도 따뜻하게 1:1 피드백해 주십시오.

    [훈련 기출 문항 정보]
    - 시험: {problem_info['exam_title']} {problem_info['q_num']}번 ({problem_info['genre']})
    - 문항 주제: {problem_info['topic']}
    - 평가원 함정 설계: {problem_info['trap_concept']}
    - 학생에게 부여된 방어 미션: {problem_info['mission']}

    [코칭 가이드라인]
    1. 학생의 방어 논리가 방어 미션 원칙에 부합하는지 명확히 평가하십시오.
    2. 지문이나 선지의 어휘를 정확히 근거로 들었는지 칭찬하거나 보완점을 짚어주십시오.
    3. 다음 실전 시험장에서도 이 원칙을 적용할 수 있도록 격려하는 한 마디를 덧붙이십시오.
    4. 친절하고 신뢰감 있는 멘토의 말투(해요체)로 작성하세요. (3~4문장)
    """

    prompt = f"학생이 작성한 방어 훈련 내용:\n\"{student_defense}\"\n\n위 내용에 대해 맞춤 코칭 피드백을 작성해 주세요."

    response = client.models.generate_content(
        model='gemini-2.5-flash',
        contents=prompt,
        config=types.GenerateContentConfig(
            system_instruction=system_prompt,
            temperature=0.3
        )
    )
    return response.text
